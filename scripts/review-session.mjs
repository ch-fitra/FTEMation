// Local browser regression for confirmation, real session changes, and feedback.
import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const { chromium } = createRequire(path.join(process.env.PLAYWRIGHT_REVIEW_ROOT ?? path.join(tmpdir(), 'ftemation-ui-review'), 'package.json'))('playwright');
const base = process.env.UI_BASE_URL ?? 'http://localhost:8000';
assert(['localhost', '127.0.0.1'].includes(new URL(base).hostname));
const env = await readFile(path.join(root, '.env'), 'utf8');
const setting = key => process.env[key] ?? env.match(new RegExp(`^${key}=(.*)$`, 'm'))?.[1].trim().replace(/^(["'])(.*)\1$/, '$2');
const output = path.join(root, 'storage/app/private/ui-review/session');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const checks = [], errors = [];
function gate() { let release; const pending = new Promise(resolve => { release = resolve; }); return { pending, release }; }
try {
 for (const [name, viewport] of [['desktop', {width:1440,height:1000}], ['mobile', {width:390,height:844}]]) {
  const context = await browser.newContext({viewport});
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/`);
  await page.getByLabel('Username', {exact:true}).fill(setting('DEMO_USERNAME'));
  await page.getByLabel('Password', {exact:true}).fill(setting('DEMO_PASSWORD'));
  assert.equal(await page.getByLabel('Username',{exact:true}).inputValue(),setting('DEMO_USERNAME'));
  assert.equal(await page.getByLabel('Email',{exact:true}).count(),0);
  assert.equal(await page.locator('#password').getAttribute('type'),'password');
  await page.getByRole('button',{name:'Tampilkan password',exact:true}).click();
  assert.equal(await page.locator('#password').getAttribute('type'),'text');
  assert.equal(await page.locator('#password').inputValue(),setting('DEMO_PASSWORD'));
  await page.getByRole('button',{name:'Sembunyikan password',exact:true}).press('Space');
  assert.equal(await page.locator('#password').getAttribute('type'),'password');
  assert.equal(await page.getByRole('dialog').count(),0);
  checks.push(`${name}/password: eye button toggles visibility without submitting or changing value`);
  await page.route('**/api/login', route => route.fulfill({status:422,json:{errors:{username:['Username atau password tidak sesuai.']}}}));
  await page.getByRole('button', {name:/^Masuk$/}).click();
  await page.getByRole('dialog', {name:'Gagal masuk'}).waitFor();
  await page.getByRole('button', {name:'OK',exact:true}).click();
  assert.equal(await page.locator('#password').count(),1);
  checks.push(`${name}/login: failure shows error, stays signed out`);
  await page.unroute('**/api/login');
  const signingIn = gate();
  await page.route('**/api/login', async route => {await signingIn.pending; await route.continue();});
  await page.getByRole('button', {name:/^Masuk$/}).click();
  await page.getByRole('button', {name:/^Memproses/}).waitFor();
  assert.equal(await page.getByRole('button', {name:/^Memproses/}).isDisabled(),true);
  assert.equal(await page.locator('#username').isDisabled(),true);
  assert.equal(await page.locator('#password').isDisabled(),true);
  assert.equal(await page.getByRole('dialog').count(),0);
  await page.screenshot({animations:'disabled',path:path.join(output,`${name}-login-pending.png`)});
  signingIn.release();
  await page.getByRole('dialog', {name:'Berhasil masuk'}).waitFor();
  await page.screenshot({animations:'disabled',path:path.join(output,`${name}-login-success.png`)});
  assert.equal(await page.getByRole('dialog').getByRole('button').count(),0);
  checks.push(`${name}/login: disabled processing button, no pending modal, automatic success popup`);
  await page.locator('.department-chart').waitFor();
  assert.equal((await page.locator('.user-menu').textContent()).trim(),'DDemo');
  checks.push(`${name}/profile: signed-in display name is Demo`);
  await page.screenshot({animations:'disabled',path:path.join(output,`${name}-workspace.png`),fullPage:true});
  assert.equal(await page.locator('.topbar button').count(),0);
  assert.equal(await page.locator('.sidebar-logout').count(),1);
  assert((await page.locator('.topbar').boundingBox()).height<=64);
  if(name==='desktop') {
   const logoutBox=await page.locator('.sidebar-logout').boundingBox();
   assert(logoutBox.y+logoutBox.height>viewport.height-40);
  }
  checks.push(`${name}/layout: compact header, sidebar logout visible`);
  const sourcePath = name === 'desktop' ? '/activities' : '/imports';
  await page.getByRole('link', {name:name==='desktop'?'Data aktivitas':'Import dataset',exact:true}).click();
  if(name==='desktop') await page.locator('tbody .activity-code').first().waitFor();
  else await page.getByRole('heading',{name:'Import workbook Excel',exact:true}).waitFor();
  assert.equal(new URL(page.url()).pathname,sourcePath);
  let logoutRequests=0;
  page.on('request', request => {if(new URL(request.url()).pathname==='/api/logout') logoutRequests++;});
  await page.getByRole('button', {name:'Keluar',exact:true}).click();
  await page.getByRole('dialog', {name:'Apakah Anda yakin?'}).waitFor();
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'hidden');
  assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Batal');
  await page.screenshot({animations:'disabled',path:path.join(output,`${name}-logout-confirm.png`)});
  await page.getByRole('button', {name:'Batal',exact:true}).click();
  assert.equal(logoutRequests,0);
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'');
  assert.equal(await page.evaluate(()=>document.activeElement.classList.contains('sidebar-logout')),true);
  checks.push(`${name}/logout: cancel keeps session, focus returns to trigger`);
  assert.equal(new URL(page.url()).pathname,sourcePath);
  await page.getByRole('button', {name:'Keluar',exact:true}).click();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(),0);
  assert.equal(logoutRequests,0);
  checks.push(`${name}/logout: Escape dismisses confirmation without request`);
  await page.route('**/api/logout', route => route.fulfill({status:503,json:{message:'Test unavailable'}}));
  await page.getByRole('button', {name:'Keluar',exact:true}).click();
  await page.getByRole('button', {name:'Yakin',exact:true}).click();
  await page.getByRole('dialog', {name:'Gagal keluar'}).waitFor();
  await page.getByRole('button', {name:'OK',exact:true}).click();
  assert.equal(await page.locator('.sidebar-logout').count(),1);
  checks.push(`${name}/logout: failed request does not show success or sign out`);
  assert.equal(new URL(page.url()).pathname,sourcePath);
  await page.unroute('**/api/logout');
  const signingOut=gate();
  await page.route('**/api/logout', async route => {await signingOut.pending;await route.continue();});
  await page.getByRole('button', {name:'Keluar',exact:true}).click();
  await page.getByRole('button', {name:'Yakin',exact:true}).click();
  await page.getByRole('dialog', {name:'Memproses...'}).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(),1);
  await page.screenshot({animations:'disabled',path:path.join(output,`${name}-logout-pending.png`)});
  signingOut.release();
  await page.getByRole('dialog', {name:'Berhasil keluar'}).waitFor();
  await page.screenshot({animations:'disabled',path:path.join(output,`${name}-logout-success.png`)});
  if(name==='mobile') await page.getByRole('button',{name:'OK',exact:true}).click();
  checks.push(`${name}/logout: confirm, pending spinner, success after response`);
  // Verify automatic return; no need for another click after the success feedback.
  await page.locator('#password').waitFor();
  assert.equal(new URL(page.url()).pathname,'/');
  assert.equal((await context.request.get(`${base}/api/user`, {headers:{Accept:'application/json'}})).status(),401);
  assert.equal(await page.locator('.sidebar').count(),0);
  checks.push(`${name}/logout: automatic return to login and server session invalidated`);
  await page.reload();
  await page.locator('#password').waitFor();
  assert.equal(new URL(page.url()).pathname,'/');
  checks.push(`${name}/logout: login URL remains root after refresh`);
  await page.goBack();
  await page.locator('#password').waitFor();
  assert.equal(new URL(page.url()).pathname,'/');
  assert.equal(await page.locator('.workspace').count(),0);
  checks.push(`${name}/logout: Back cannot restore a signed-out private page`);
  await context.close();
 }
 assert.deepEqual(errors,[]);
 await writeFile(path.join(output,'report.json'),JSON.stringify({checks,errors},null,2));
 console.log(JSON.stringify({checks:checks.length,runtimeErrors:errors.length,screenshots:output}));
} finally {await browser.close();}
